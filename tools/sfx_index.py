"""Index the shared SFX library (library/sfx) -> library/sfx/index.json.

Usage:  tools/.venv/bin/python tools/sfx_index.py [library/sfx]

Per file: category (folder path), duration, peak dBFS, loudest-100ms RMS dB, hit time (loudest
instant, where the accent lands -> align this to the picture event), effective length (until -40 dB
below peak), spectral centroid around the hit (Hz) and share of energy above 4 kHz, plus coarse tags:
  bright (centroid >= 3000) / dark (<= 900), transient (hit < 60 ms, short), riser (hit > 0.8 s), long (> 4 s).
I can't listen: tags are measurements, pick by name + tags, then A/B in context.
"""
import json, os, subprocess, sys

import numpy as np

ROOT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "library", "sfx")
EXT = (".wav", ".mp3", ".aac", ".m4a", ".webm", ".mp4", ".ogg", ".aif", ".aiff", ".flac")
SR = 22050


def decode(path):
    r = subprocess.run(["ffmpeg", "-v", "error", "-i", path, "-vn", "-ac", "1", "-ar", str(SR), "-f", "f32le", "-"],
                       capture_output=True)
    return np.frombuffer(r.stdout, dtype=np.float32)


def db(x):
    return round(float(20 * np.log10(max(x, 1e-9))), 1)


def analyse(x):
    n = len(x)
    if n < SR // 50:
        return None
    a = np.abs(x)
    peak = float(a.max())
    win = SR // 10
    env = np.sqrt(np.convolve(x * x, np.ones(win) / win, mode="same"))
    hit = int(np.argmax(env))
    above = np.nonzero(env > env[hit] * 10 ** (-40 / 20))[0]
    eff = (above[-1] - above[0]) / SR if len(above) else 0
    seg = x[max(0, hit - int(0.15 * SR)): hit + int(0.15 * SR)]
    spec = np.abs(np.fft.rfft(seg * np.hanning(len(seg)))) ** 2
    f = np.fft.rfftfreq(len(seg), 1 / SR)
    cen = float((spec * f).sum() / max(spec.sum(), 1e-12))
    hf = float(spec[f >= 4000].sum() / max(spec.sum(), 1e-12))
    d = {"dur": round(n / SR, 3), "peakDb": db(peak), "rmsDb": db(float(env[hit])), "hit": round(hit / SR, 3),
         "effLen": round(eff, 3), "centroidHz": int(cen), "hfShare": round(hf, 3)}
    tags = []
    if cen >= 3000:
        tags.append("bright")
    elif cen <= 900:
        tags.append("dark")
    if d["hit"] < 0.06 and d["effLen"] < 1.0:
        tags.append("transient")
    if d["hit"] > 0.8:
        tags.append("riser")
    if d["dur"] > 4:
        tags.append("long")
    d["tags"] = tags
    return d


items = []
for dp, dns, fns in os.walk(ROOT):
    dns[:] = sorted(d for d in dns if not d.startswith("_"))  # skip "_Mister Horse Previews" (png only)
    for fn in sorted(fns):
        if not fn.lower().endswith(EXT):
            continue
        p = os.path.join(dp, fn)
        rel = os.path.relpath(p, ROOT)
        d = analyse(decode(p))
        if d:
            items.append({"path": rel, "category": os.path.dirname(rel), "name": os.path.splitext(fn)[0], **d})
out = os.path.join(ROOT, "index.json")
with open(out, "w", encoding="utf-8") as f:
    json.dump({"_note": "generated by tools/sfx_index.py; paths relative to library/sfx", "items": items}, f, ensure_ascii=False, indent=0)
print(f"{len(items)} sounds -> {out}")
